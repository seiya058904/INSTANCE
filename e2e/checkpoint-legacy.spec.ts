import { expect, test } from '@playwright/test'

test('existing v2 progress upgrades safely and a v1 writer blocks play across tabs and reload', async ({ page, context }) => {
  await page.goto('/?qaPacing=instant')
  await expect(page.locator('.candidate-response').first()).toBeEnabled()
  await expect.poll(() => page.evaluate(() => localStorage.getItem('instance:checkpoint:v2'))).not.toBeNull()
  await page.locator('.candidate-response').first().click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('instance:checkpoint:v2')!).data.run.history.length)).toBe(1)
  const before = await page.evaluate(() => {
    const envelope = JSON.parse(localStorage.getItem('instance:checkpoint:v2')!)
    envelope.legacy = JSON.stringify(JSON.parse(envelope.legacy).slice(0, 5))
    localStorage.setItem('instance:checkpoint:v1', 'preserved-old-edition')
    localStorage.setItem('instance:checkpoint:v2', JSON.stringify(envelope))
    return envelope.data.run
  })
  await page.reload()
  await expect(page.locator('.candidate-response').first()).toBeEnabled()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('instance:checkpoint:v2')!).data.run)).toEqual(before)
  await page.locator('.candidate-response').first().click()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('instance:checkpoint:v2')!).data.run.history.length)).toBe(2)
  const saved = await page.evaluate(() => localStorage.getItem('instance:checkpoint:v2'))
  expect(JSON.parse(JSON.parse(saved!).legacy)).toHaveLength(6)
  expect(await page.evaluate(() => localStorage.getItem('instance:checkpoint:v1'))).toBe('preserved-old-edition')
  const other = await context.newPage()
  await other.goto('/?qaPacing=instant')
  await expect(other.locator('.candidate-response').first()).toBeEnabled()
  await other.evaluate(() => localStorage.setItem('instance:checkpoint:v1', 'old-tab-new-progress'))
  await page.bringToFront()
  await expect(page.getByRole('button', { name: '读取最新进度', exact: true })).toBeVisible()
  expect(await page.locator('.checkpoint-content').getAttribute('inert')).not.toBeNull()
  expect(await page.evaluate(() => localStorage.getItem('instance:checkpoint:v2'))).toBe(saved)
  await page.reload()
  await expect(page.getByRole('button', { name: '读取最新进度', exact: true })).toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem('instance:checkpoint:v2'))).toBe(saved)
  expect(await page.evaluate(() => localStorage.getItem('instance:checkpoint:v1'))).toBe('old-tab-new-progress')
})
